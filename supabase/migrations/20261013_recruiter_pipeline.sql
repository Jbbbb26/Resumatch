-- Run after 20261013_job_listing_archive_and_hiring_status.sql.
-- Add hiring stages and auditable stage history to existing applications.
-- Existing application rows are retained and mapped from their current status.

alter table public.applications
  add column if not exists stage text not null default 'applied',
  add column if not exists stage_updated_at timestamptz not null default now(),
  add column if not exists rejection_reason text,
  add column if not exists notes text;

update public.applications
set stage = case lower(coalesce(status, 'applied'))
  when 'screening' then 'screening'
  when 'interview' then 'interview'
  when 'offer' then 'offer'
  when 'hired' then 'hired'
  when 'rejected' then 'rejected'
  else 'applied'
end
where stage = 'applied';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'applications_stage_check'
      and conrelid = 'public.applications'::regclass
  ) then
    alter table public.applications
      add constraint applications_stage_check
      check (stage in ('applied', 'screening', 'interview', 'offer', 'hired', 'rejected'));
  end if;
end $$;

create table if not exists public.application_stage_history (
  id bigint generated by default as identity primary key,
  application_id uuid not null references public.applications(id) on delete cascade,
  from_stage text,
  to_stage text not null check (to_stage in ('applied', 'screening', 'interview', 'offer', 'hired', 'rejected')),
  changed_by uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now(),
  note text
);

alter table public.applications enable row level security;
alter table public.application_stage_history enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'applications'
      and policyname = 'Recruiters can read pipeline applications'
  ) then
    create policy "Recruiters can read pipeline applications"
      on public.applications for select to authenticated
      using (exists (
        select 1 from public.job_postings j
        where j.id = applications.job_id and j.recruiter_id = auth.uid()
      ));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'applications'
      and policyname = 'Recruiters can update pipeline applications'
  ) then
    create policy "Recruiters can update pipeline applications"
      on public.applications for update to authenticated
      using (exists (
        select 1 from public.job_postings j
        where j.id = applications.job_id and j.recruiter_id = auth.uid()
      ))
      with check (exists (
        select 1 from public.job_postings j
        where j.id = applications.job_id and j.recruiter_id = auth.uid()
      ));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'application_stage_history'
      and policyname = 'Recruiters can read pipeline stage history'
  ) then
    create policy "Recruiters can read pipeline stage history"
      on public.application_stage_history for select to authenticated
      using (exists (
        select 1
        from public.applications a
        join public.job_postings j on j.id = a.job_id
        where a.id = application_stage_history.application_id
          and j.recruiter_id = auth.uid()
      ));
  end if;
end $$;

create or replace function public.record_application_stage_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.application_stage_history (application_id, from_stage, to_stage, changed_by, note)
    values (
      new.id,
      null,
      new.stage,
      auth.uid(),
      case when new.stage = 'rejected' then new.rejection_reason end
    );
  elsif new.stage is distinct from old.stage then
    insert into public.application_stage_history (application_id, from_stage, to_stage, changed_by, note)
    values (
      new.id,
      old.stage,
      new.stage,
      auth.uid(),
      case when new.stage = 'rejected' then new.rejection_reason end
    );
  end if;
  return new;
end;
$$;

create or replace function public.touch_application_stage_updated_at()
returns trigger
language plpgsql
as $$
begin
  if new.stage is distinct from old.stage then
    new.stage_updated_at := now();
  end if;
  return new;
end;
$$;

drop trigger if exists applications_touch_stage_updated_at on public.applications;
create trigger applications_touch_stage_updated_at
  before update of stage on public.applications
  for each row execute function public.touch_application_stage_updated_at();

drop trigger if exists applications_record_stage_insert on public.applications;
create trigger applications_record_stage_insert
  after insert on public.applications
  for each row execute function public.record_application_stage_change();

drop trigger if exists applications_record_stage_update on public.applications;
create trigger applications_record_stage_update
  after update of stage on public.applications
  for each row execute function public.record_application_stage_change();
drop trigger if exists applications_record_stage_change on public.applications;

-- Recruiters may move existing applicants between stages even if the job is
-- closed; the candidate-side closed-job application guard remains in place.
create or replace function public.prevent_application_to_closed_job()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  should_validate boolean;
begin
  if tg_op = 'INSERT' then
    should_validate := true;
  else
    should_validate := new.status = 'Applied'
      and (old.status is distinct from new.status or old.job_id is distinct from new.job_id);
  end if;

  if should_validate
    and not exists (
      select 1 from public.job_postings
      where id = new.job_id and recruiter_id = auth.uid()
    )
    and not exists (
      select 1 from public.job_postings
      where id = new.job_id
        and coalesce(status, 'active') = 'active'
        and coalesce(is_archived, false) = false
        and coalesce(hiring_status, 'open') = 'open'
    ) then
    raise exception 'This position is no longer accepting applications.';
  end if;
  return new;
end;
$$;
